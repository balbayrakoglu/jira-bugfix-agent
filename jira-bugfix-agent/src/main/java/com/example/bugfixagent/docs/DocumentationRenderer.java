package com.example.bugfixagent.docs;

import com.example.bugfixagent.ai.BugAnalysis;
import com.example.bugfixagent.ai.FileEdit;
import com.example.bugfixagent.repo.BuildVerifier;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.Locale;

public final class DocumentationRenderer {

    private static final DateTimeFormatter TIMESTAMP =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'").withZone(ZoneOffset.UTC);

    private DocumentationRenderer() {
    }

    public static String markdown(BugReport report) {
        BugAnalysis a = report.analysis();
        var md = new StringBuilder();
        md.append("# ").append(report.issue().key()).append(": ").append(oneLine(report.issue().summary())).append("\n\n");
        md.append("| | |\n|---|---|\n")
                .append("| Jira | [").append(report.issue().key()).append("](").append(report.issueUrl()).append(") |\n")
                .append("| Priority | ").append(report.issue().priority()).append(" |\n")
                .append("| Mode | ").append(modeLabel(report)).append(" |\n")
                .append("| Risk | ").append(a.riskLevel()).append(" |\n")
                .append("| Confidence | ").append(percent(a.confidence())).append(" |\n")
                .append("| Verification | ").append(verificationLabel(report.verification())).append(" |\n")
                .append("| Generated | ").append(TIMESTAMP.format(report.generatedAt())).append(" |\n\n");

        section(md, "Summary", a.summary());
        section(md, "Root cause", a.rootCause());
        if (!a.affectedComponents().isEmpty()) {
            md.append("## Affected components\n\n");
            a.affectedComponents().forEach(c -> md.append("- `").append(c).append("`\n"));
            md.append('\n');
        }
        section(md, "Fix", a.fixDescription());

        if (a.hasEdits()) {
            md.append(report.codeChanged() ? "## Code changes\n\n" : "## Suggested code changes (not applied)\n\n");
            for (FileEdit edit : a.edits()) {
                md.append("### `").append(edit.path()).append("`\n\n");
                if (!edit.explanation().isBlank()) {
                    md.append(edit.explanation()).append("\n\n");
                }
                if (!edit.createsNewFile()) {
                    md.append("Before:\n\n").append(fenced(edit.oldText(), language(edit.path()))).append('\n');
                }
                md.append(edit.createsNewFile() ? "New file:\n\n" : "After:\n\n")
                        .append(fenced(edit.newText(), language(edit.path()))).append('\n');
            }
        }

        section(md, "How to verify", a.testingNotes());
        if (report.downgradeReason() != null) {
            section(md, "Why the fix was not applied automatically", report.downgradeReason());
        }
        if (!a.openQuestions().isEmpty()) {
            md.append("## Open questions\n\n");
            a.openQuestions().forEach(q -> md.append("- ").append(oneLine(q)).append('\n'));
            md.append('\n');
        }
        md.append("---\n_Generated by the AI Bugfix Agent. Review before merging._\n");
        return md.toString();
    }

    public static String pullRequestBody(BugReport report, String markdownPath) {
        BugAnalysis a = report.analysis();
        var md = new StringBuilder();
        md.append("Fixes [").append(report.issue().key()).append("](").append(report.issueUrl()).append(")\n\n");
        md.append(report.codeChanged()
                ? "> 🤖 This PR was generated by the AI Bugfix Agent. **Human review is required before merge.**\n\n"
                : "> 🤖 Documentation-only PR: the agent analysed the bug but did **not** change code.\n\n");
        section(md, "Summary", a.summary());
        section(md, "Root cause", a.rootCause());
        section(md, "Fix", a.fixDescription());
        if (report.codeChanged()) {
            md.append("## Changed files\n\n");
            report.changedFiles().forEach(f -> md.append("- `").append(f).append("`\n"));
            md.append('\n');
        }
        md.append("## Verification\n\n").append(verificationLabel(report.verification())).append("\n\n");
        section(md, "How to verify", a.testingNotes());
        md.append("Risk: **").append(a.riskLevel()).append("** · Confidence: **").append(percent(a.confidence()))
                .append("**\n\nFull write-up: `").append(markdownPath).append("`\n");
        return md.toString();
    }

    public static String confluenceStorage(BugReport report, BugReport.Links links) {
        BugAnalysis a = report.analysis();
        var html = new StringBuilder();
        html.append("<table><tbody>")
                .append(row("Jira", "<a href=\"" + xml(report.issueUrl()) + "\">" + xml(report.issue().key()) + "</a>"))
                .append(row("Priority", xml(report.issue().priority())))
                .append(row("Mode", xml(modeLabel(report))))
                .append(row("Risk", xml(a.riskLevel().name())))
                .append(row("Confidence", xml(percent(a.confidence()))))
                .append(row("Verification", xml(verificationLabel(report.verification()))));
        if (links.pullRequestUrl() != null) {
            html.append(row("Pull request", "<a href=\"" + xml(links.pullRequestUrl()) + "\">" + xml(links.pullRequestUrl()) + "</a>"));
        }
        html.append(row("Generated", xml(TIMESTAMP.format(report.generatedAt())))).append("</tbody></table>");

        htmlSection(html, "Summary", a.summary());
        htmlSection(html, "Root cause", a.rootCause());
        if (!a.affectedComponents().isEmpty()) {
            html.append("<h2>Affected components</h2><ul>");
            a.affectedComponents().forEach(c -> html.append("<li><code>").append(xml(c)).append("</code></li>"));
            html.append("</ul>");
        }
        htmlSection(html, "Fix", a.fixDescription());
        if (a.hasEdits()) {
            html.append(report.codeChanged() ? "<h2>Code changes</h2>" : "<h2>Suggested code changes (not applied)</h2>");
            for (FileEdit edit : a.edits()) {
                html.append("<h3><code>").append(xml(edit.path())).append("</code></h3>");
                if (!edit.explanation().isBlank()) {
                    html.append(paragraphs(edit.explanation()));
                }
                if (!edit.createsNewFile()) {
                    html.append("<p>Before:</p>").append(codeMacro(edit.oldText(), language(edit.path())));
                }
                html.append(edit.createsNewFile() ? "<p>New file:</p>" : "<p>After:</p>")
                        .append(codeMacro(edit.newText(), language(edit.path())));
            }
        }
        htmlSection(html, "How to verify", a.testingNotes());
        if (report.downgradeReason() != null) {
            htmlSection(html, "Why the fix was not applied automatically", report.downgradeReason());
        }
        if (!a.openQuestions().isEmpty()) {
            html.append("<h2>Open questions</h2><ul>");
            a.openQuestions().forEach(q -> html.append("<li>").append(xml(q)).append("</li>"));
            html.append("</ul>");
        }
        return html.toString();
    }

    public static String jiraComment(BugReport report, BugReport.Links links) {
        BugAnalysis a = report.analysis();
        var wiki = new StringBuilder();
        wiki.append("h3. 🤖 AI Bugfix Agent — ").append(modeLabel(report)).append("\n\n");
        wiki.append("*Summary:* ").append(a.summary()).append("\n\n");
        wiki.append("*Root cause:* ").append(a.rootCause()).append("\n\n");
        wiki.append("*Fix:* ").append(a.fixDescription()).append("\n\n");
        wiki.append("*Risk:* ").append(a.riskLevel())
                .append(" | *Confidence:* ").append(percent(a.confidence()))
                .append(" | *Verification:* ").append(verificationLabel(report.verification())).append("\n\n");

        if (links.pullRequestUrl() != null) {
            wiki.append("*Pull request:* [").append(links.pullRequestUrl()).append("]\n");
        }
        if (links.confluenceUrl() != null) {
            wiki.append("*Documentation:* [").append(links.confluenceUrl()).append("]\n");
        }
        if (links.markdownPath() != null) {
            wiki.append("*Repo doc:* {{").append(links.markdownPath()).append("}}\n");
        }
        if (report.downgradeReason() != null) {
            wiki.append("\n*Not applied automatically:* ").append(report.downgradeReason()).append('\n');
        }
        if (!report.codeChanged() && a.hasEdits()) {
            wiki.append("\nh4. Suggested change\n");
            for (FileEdit edit : a.edits()) {
                wiki.append("*").append(edit.path()).append("*\n")
                        .append("{code:").append(language(edit.path())).append("}\n")
                        .append(edit.newText().replace("{code}", "{ code}"))
                        .append("\n{code}\n");
            }
        }
        if (!a.openQuestions().isEmpty()) {
            wiki.append("\nh4. Open questions\n");
            a.openQuestions().forEach(q -> wiki.append("* ").append(oneLine(q)).append('\n'));
        }
        return wiki.toString();
    }

    static String modeLabel(BugReport report) {
        if (report.requestedMode() == report.effectiveMode()) {
            return report.effectiveMode().label();
        }
        return report.effectiveMode().label() + " (requested: " + report.requestedMode().label() + ")";
    }

    static String verificationLabel(BuildVerifier.Result result) {
        if (result == null) {
            return "Not run";
        }
        if (result.skipped()) {
            return "Skipped";
        }
        return result.success() ? "Passed ✅" : "Failed ❌ (exit " + result.exitCode() + ")";
    }

    static String fenced(String code, String language) {
        String fence = "```";
        while (code.contains(fence)) {
            fence += "`";
        }
        return fence + language + "\n" + code + (code.endsWith("\n") ? "" : "\n") + fence + "\n";
    }

    static String codeMacro(String code, String language) {
        String cdata = code.replace("]]>", "]]]]><![CDATA[>");
        return "<ac:structured-macro ac:name=\"code\"><ac:parameter ac:name=\"language\">" + xml(language)
                + "</ac:parameter><ac:plain-text-body><![CDATA[" + cdata + "]]></ac:plain-text-body></ac:structured-macro>";
    }

    static String xml(String text) {
        if (text == null) {
            return "";
        }
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    static String language(String path) {
        String lower = path.toLowerCase(Locale.ROOT);
        if (lower.endsWith(".java")) return "java";
        if (lower.endsWith(".kt")) return "kotlin";
        if (lower.endsWith(".yml") || lower.endsWith(".yaml")) return "yaml";
        if (lower.endsWith(".xml")) return "xml";
        if (lower.endsWith(".sql")) return "sql";
        if (lower.endsWith(".properties")) return "properties";
        return "text";
    }

    private static void section(StringBuilder md, String title, String body) {
        if (body != null && !body.isBlank()) {
            md.append("## ").append(title).append("\n\n").append(body.strip()).append("\n\n");
        }
    }

    private static void htmlSection(StringBuilder html, String title, String body) {
        if (body != null && !body.isBlank()) {
            html.append("<h2>").append(xml(title)).append("</h2>").append(paragraphs(body));
        }
    }

    private static String paragraphs(String text) {
        var html = new StringBuilder();
        for (String paragraph : text.strip().split("\\R\\s*\\R")) {
            html.append("<p>").append(xml(paragraph).replaceAll("\\R", "<br/>")).append("</p>");
        }
        return html.toString();
    }

    private static String row(String header, String valueHtml) {
        return "<tr><th>" + xml(header) + "</th><td>" + valueHtml + "</td></tr>";
    }

    private static String oneLine(String text) {
        return text == null ? "" : text.replaceAll("\\s*\\R\\s*", " ").strip();
    }

    private static String percent(double value) {
        return Math.round(value * 100) + "%";
    }
}
